jari_jari_alas = float(input("masukkan jari-jari kerucut:"))
Tinggi_kerucut = float(input("masukkan tinggi kerucut:"))

pi = 22/7

volume = (1/3) * pi * (jari_jari_alas ** 2) * Tinggi_kerucut
print("===menghitung volume kerucut===")
print("jari jari :", jari_jari_alas, "cm")
print("tinggi :", Tinggi_kerucut, "cm")
print("volume :", volume, "cm")